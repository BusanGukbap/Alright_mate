import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

import openapiTS, { astToString } from "openapi-typescript";
import { describe, expect, it } from "vitest";

describe("generated OpenAPI schema", () => {
  it("matches the checked-in root contract", async () => {
    const specificationPath = resolve(process.cwd(), "../../specs/openapi.yaml");
    const schema = await openapiTS(await readFile(specificationPath));
    const checkedIn = await readFile(resolve(process.cwd(), "src/api/schema.d.ts"), "utf8");

    const generatedBanner = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

    expect(`${generatedBanner}${astToString(schema)}`).toBe(checkedIn);
  });
});
